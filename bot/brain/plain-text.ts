/**
 * Привести ответ LLM к house-style plain text: Telegram и вебчат показывают
 * текст как есть (sendMessage без parse_mode, textContent на фронте), поэтому
 * markdown доезжает до пользователя сырыми звёздочками. Промт markdown
 * запрещает, но модель всё равно присылает — чистим в единственной точке
 * выхода ответа (brain.answer, llm-ветка): история в Redis тоже получает
 * чистый текст, и LLM перестаёт видеть свои «**» на следующих ходах.
 *
 * Набор правил минимальный и детерминированный — ровно то, что реально
 * приходит от модели. Непарные маркеры и экзотика (таблицы) не трогаются:
 * испортить честный текст хуже, чем оставить редкую звёздочку.
 */

// Парные инлайн-маркеры: **жирный**, __жирный__, `код`. Нежадные, в пределах
// строки («.» не съедает \n) — маркер, открытый и не закрытый в строке, не парой.
const BOLD_RE = /\*\*(.+?)\*\*/g;
const UNDERBOLD_RE = /__(.+?)__/g;
const CODE_RE = /`([^`]+)`/g;

// Буллет «- » или «* » в начале строки → символ домостиля (как в help.ts).
// «*» без пробела за ней («**жирный» или «*курсив») буллетом не считается.
const BULLET_RE = /^[-*] /;

// Заголовок atx-вида «### Текст» → просто строка «Текст».
const HEADER_RE = /^#{1,6} /;

/**
 * Очистить markdown-разметку до plain text.
 * @param {string} md - Ответ модели (возможно, с markdown).
 * @returns {string} Текст для показа пользователю: без звёздочек/решёток,
 *   списки — буллетом «•».
 */
export function toPlainText(md: string): string {
  return md
    .split("\n")
    .map((line) => line.replace(HEADER_RE, "").replace(BULLET_RE, "• "))
    .join("\n")
    .replace(BOLD_RE, "$1")
    .replace(UNDERBOLD_RE, "$1")
    .replace(CODE_RE, "$1");
}
