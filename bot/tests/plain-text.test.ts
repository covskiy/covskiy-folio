import { describe, expect, it } from "vitest";
import { toPlainText } from "../brain/plain-text";

describe("toPlainText: инлайн-маркеры", () => {
  it("**жирный** → содержимое", () => {
    expect(toPlainText("**PWA-приложения** — устанавливаются на телефон")).toBe(
      "PWA-приложения — устанавливаются на телефон",
    );
  });

  it("__жирный__ → содержимое", () => {
    expect(toPlainText("__важный__ пункт")).toBe("важный пункт");
  });

  it("`код` → содержимое", () => {
    expect(toPlainText("стек: `React, TS, GSAP`")).toBe("стек: React, TS, GSAP");
  });

  it("несколько пар в одной строке", () => {
    expect(toPlainText("**a** и **b**, а также `c`")).toBe("a и b, а также c");
  });

  it("непарный маркер не тронут", () => {
    expect(toPlainText("это * просто звёздочка в тексте")).toBe("это * просто звёздочка в тексте");
  });

  it("одиночные *…* сознательно не трогаются (риск испортить честный текст)", () => {
    expect(toPlainText("умножение 2 * 3 = 6")).toBe("умножение 2 * 3 = 6");
  });

  it("маркер, не закрытый в строке, остаётся (пара ищется в пределах строки)", () => {
    expect(toPlainText("**начало жирного\nи продолжение")).toBe("**начало жирного\nи продолжение");
  });
});

describe("toPlainText: строки", () => {
  it("дефис-буллет → «•»", () => {
    expect(toPlainText("- пункт один")).toBe("• пункт один");
  });

  it("звёздочка-буллет → «•»", () => {
    expect(toPlainText("* пункт два")).toBe("• пункт два");
  });

  it("жирный внутри буллета чистится вместе", () => {
    expect(toPlainText("- **фронтенд** — вёрстка")).toBe("• фронтенд — вёрстка");
  });

  it("тире в тексте не принимается за буллет", () => {
    expect(toPlainText("пример — длинное тире")).toBe("пример — длинное тире");
  });

  it("заголовок ### → строка без решёток", () => {
    expect(toPlainText("### Опыт работы")).toBe("Опыт работы");
  });

  it("хэштег без пробела после решёток не заголовок", () => {
    expect(toPlainText("#тег")).toBe("#тег");
  });
});

describe("toPlainText: целые ответы", () => {
  it("многострочный микс из реального ответа LLM", () => {
    const md = [
      "Я — Константин Ковский, независимый разработчик.",
      "",
      "Мои основные направления:",
      "- **PWA-приложения** — устанавливаются на телефон;",
      "- фронтенд — вёрстка, анимации.",
      "",
      "### Что дальше",
      "Напишите в Telegram: `@devCovskiy`.",
    ].join("\n");

    const out = toPlainText(md);

    expect(out.split("\n")[3]).toBe("• PWA-приложения — устанавливаются на телефон;");
    expect(out.split("\n")[4]).toBe("• фронтенд — вёрстка, анимации.");
    expect(out.split("\n")[6]).toBe("Что дальше");
    expect(out.split("\n")[7]).toBe("Напишите в Telegram: @devCovskiy.");
    expect(out).not.toContain("**");
    expect(out).not.toContain("#");
    expect(out).not.toContain("`");
  });

  it("текст без markdown не изменён", () => {
    const t = "Привет! Я справочный бот.\nВторая строка.";
    expect(toPlainText(t)).toBe(t);
  });
});
